import { fireEvent, render, screen, waitFor, within } from '@testing-library/vue'
import { flushPromises } from '@vue/test-utils'
import { createMemoryHistory, createRouter } from 'vue-router'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import PostListView from '@/views/PostListView.vue'
import { emptyPost } from '@/data/post-fields'
const mocks = vi.hoisted(() => ({ list: vi.fn(), save: vi.fn(), remove: vi.fn(), duplicate: vi.fn(), download: vi.fn(), media: vi.fn() }))
vi.mock('@/api/post-catalog', () => ({ createPostCatalog: () => mocks }))
vi.mock('@/data/product-fields', () => ({ downloadDataUrl: mocks.download }))
vi.mock('@/api/media-assets', () => ({ fetchMediaBlob: mocks.media }))
function deferred<T>() { let resolve!: (value: T) => void; const promise = new Promise<T>((done) => { resolve = done }); return { promise, resolve } }
async function mount() {
  const router = createRouter({ history: createMemoryHistory(), routes: [{ path: '/:pathMatch(.*)*', component: { template: '<div />' } }] })
  await router.push('/operations/post-management/post-management-03')
  render(PostListView, { global: { plugins: [router], stubs: { MediaThumb: true } } })
  await flushPromises()
}
beforeEach(() => {
  vi.clearAllMocks()
  localStorage.clear()
  mocks.list.mockReset().mockResolvedValue([emptyPost({ id: 'a', title: 'Alpha', body: 'old .* old' }), emptyPost({ id: 'b', title: 'Beta', body: 'old second' }), emptyPost({ id: 'c', title: 'Gamma', body: 'old third' })])
  mocks.save.mockReset().mockImplementation(async ({ post }) => post)
  mocks.remove.mockReset().mockResolvedValue(undefined)
  mocks.duplicate.mockReset().mockResolvedValue(emptyPost({ id: 'copy', title: 'Alpha 副本' }))
})
describe('post list batch and navigation boundaries', () => {
  it('previews literal replacement without writes, freezes chosen targets and saves only changed records', async () => {
    await mount()
    await fireEvent.click(screen.getByLabelText('选择 Alpha'))
    await fireEvent.click(screen.getByRole('button', { name: '替换内容' }))
    await fireEvent.update(screen.getByLabelText('查找原文'), '.*')
    await fireEvent.update(screen.getByLabelText('替换文本'), '$1')
    expect(screen.getByText('命中 1 条帖子')).toBeTruthy()
    expect(screen.getByText('old $1 old')).toBeTruthy()
    expect(mocks.save).not.toHaveBeenCalled()
    // Even a programmatic background selection change must not alter the frozen target list.
    await fireEvent.click(screen.getByLabelText('选择 Beta'))
    await fireEvent.click(screen.getByRole('button', { name: '确认保存修改' }))
    await waitFor(() => expect(screen.queryByRole('dialog')).toBeNull())
    expect(mocks.save).toHaveBeenCalledTimes(1)
    expect(mocks.save.mock.calls[0]![0]).toMatchObject({ id: 'a', post: { body: 'old $1 old' } })
  })
  it('keeps source records unchanged until success and separates uncertain from unattempted without replay', async () => {
    const originals = [emptyPost({ id: 'a', title: 'Alpha', body: 'a' }), emptyPost({ id: 'b', title: 'Beta', body: 'b' }), emptyPost({ id: 'c', title: 'Gamma', body: 'c' })]
    mocks.list.mockResolvedValue(originals)
    const save = deferred<ReturnType<typeof emptyPost>>()
    mocks.save.mockReturnValueOnce(save.promise).mockRejectedValueOnce(new Error('timeout'))
    await mount()
    await fireEvent.click(screen.getByLabelText('选择本页帖子'))
    await fireEvent.click(screen.getByRole('button', { name: '追加描述' }))
    await fireEvent.update(screen.getByLabelText('追加文本'), '+')
    await fireEvent.click(screen.getByRole('button', { name: '确认保存修改' }))
    await fireEvent.click(screen.getByRole('button', { name: '正在处理…' }))
    expect(mocks.save).toHaveBeenCalledTimes(1)
    expect(originals.map((post) => post.body)).toEqual(['a', 'b', 'c'])
    await fireEvent.update(screen.getByLabelText('追加文本'), 'changed')
    save.resolve({ ...originals[0]!, body: 'a+' })
    await waitFor(() => expect(screen.queryByRole('dialog')).toBeNull())
    expect(mocks.save).toHaveBeenCalledTimes(2)
    expect(mocks.save.mock.calls[1]![0].post.body).toBe('b+')
    const results = screen.getByRole('list', { name: '批量处理结果' })
    expect(results.textContent).toContain('Alpha：已确认成功')
    expect(results.textContent).toContain('Beta：结果待核实')
    expect(results.textContent).toContain('Gamma：尚未尝试')
    expect((screen.getByLabelText('选择 Beta') as HTMLInputElement).disabled).toBe(true)
    expect(screen.getByText(/已选 0 条/)).toBeTruthy()
    await fireEvent.click(screen.getByRole('button', { name: '刷新列表' }))
    await flushPromises()
    expect(mocks.save).toHaveBeenCalledTimes(2)
    expect((screen.getByLabelText('选择 Beta') as HTMLInputElement).disabled).toBe(true)
  })
  it('requires archive confirmation and guards duplicate submission', async () => {
    const remove = deferred<void>()
    mocks.remove.mockReturnValueOnce(remove.promise)
    await mount()
    await fireEvent.click(screen.getByRole('button', { name: '归档 Alpha' }))
    expect(mocks.remove).not.toHaveBeenCalled()
    expect(screen.getByText(/本页不提供恢复功能/)).toBeTruthy()
    await fireEvent.click(within(screen.getByRole('dialog')).getByRole('button', { name: '确认归档' }))
    await fireEvent.click(screen.getByRole('button', { name: '正在处理…' }))
    expect(mocks.remove).toHaveBeenCalledTimes(1)
    expect(mocks.remove).toHaveBeenCalledWith(['a'])
    remove.resolve()
    await waitFor(() => expect(screen.queryByRole('dialog')).toBeNull())
    expect(screen.queryByLabelText('选择 Alpha')).toBeNull()
  })
  it('surfaces duplicate errors and locks the uncertain request instead of retrying', async () => {
    mocks.duplicate.mockRejectedValueOnce(new Error('copy uncertain'))
    await mount()
    await fireEvent.click(screen.getByRole('button', { name: '复制 Alpha' }))
    await waitFor(() => expect(screen.getByRole('alert').textContent).toContain('copy uncertain'))
    expect((screen.getByRole('button', { name: '复制 Alpha' }) as HTMLButtonElement).disabled).toBe(true)
    expect(mocks.duplicate).toHaveBeenCalledTimes(1)
  })
  it('distinguishes load failure, true empty and no match, with retry', async () => {
    mocks.list.mockRejectedValueOnce(new Error('read failed')).mockResolvedValueOnce([])
    await mount()
    expect(screen.getByRole('alert').textContent).toContain('read failed')
    expect(screen.queryByText(/还没有帖子/)).toBeNull()
    await fireEvent.click(screen.getByRole('button', { name: '重试加载' }))
    expect(await screen.findByText(/还没有帖子/)).toBeTruthy()
    await fireEvent.click(screen.getByRole('button', { name: '刷新列表' }))
    await flushPromises()
    await fireEvent.update(screen.getByLabelText('搜索帖子标题、内容'), 'no match')
    expect(screen.getByText('没有符合筛选条件的帖子。')).toBeTruthy()
    await fireEvent.click(screen.getByRole('button', { name: '还原筛选' }))
    expect(screen.getByRole('button', { name: 'Alpha' })).toBeTruthy()
  })
  it('clamps pages and preserves visible cross-page selection counts', async () => {
    mocks.list.mockResolvedValue(Array.from({ length: 12 }, (_, index) => emptyPost({ id: String(index), title: 'Entry ' + index })))
    await mount()
    await fireEvent.click(screen.getByLabelText('选择 Entry 0'))
    await fireEvent.update(screen.getByLabelText('跳转页码'), '999')
    await fireEvent.click(screen.getByRole('button', { name: '确定' }))
    expect(screen.getByText('第 2 / 2 页')).toBeTruthy()
    expect(screen.getByText(/已选 1 条/)).toBeTruthy()
    await fireEvent.update(screen.getByLabelText('搜索帖子标题、内容'), 'Entry 0')
    expect(screen.getByText('第 1 / 1 页')).toBeTruthy()
    expect((screen.getByLabelText('选择 Entry 0') as HTMLInputElement).checked).toBe(true)
  })
  it('shows full details, contains keyboard focus and restores focus on Escape', async () => {
    await mount()
    const opener = screen.getByRole('button', { name: 'Alpha' })
    opener.focus()
    await fireEvent.click(opener)
    const dialog = screen.getByRole('dialog')
    expect(within(dialog).getByText('old .* old')).toBeTruthy()
    const close = within(dialog).getByRole('button', { name: '关闭' })
    expect(document.activeElement).toBe(close)
    await fireEvent.keyDown(close, { key: 'Tab' })
    expect(document.activeElement).toBe(close)
    await fireEvent.keyDown(close, { key: 'Escape' })
    expect(screen.queryByRole('dialog')).toBeNull()
    expect(document.activeElement).toBe(opener)
  })
  it('neutralizes spreadsheet formulas in all exported user fields', async () => {
    mocks.list.mockResolvedValue([emptyPost({ title: ' =SUM(1)', body: '+payload', notes: '@command', location: '-formula' })])
    await mount()
    await fireEvent.click(screen.getByRole('button', { name: '导出当前筛选' }))
    const csv = decodeURIComponent(mocks.download.mock.calls[0]![0])
    for (const value of [' =SUM(1)', '+payload', '@command', '-formula']) expect(csv).toContain('"\'' + value + '"')
  })
})
